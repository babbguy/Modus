# Output token threshold: below this avg suggests simple/classification tasks
_LOW_OUTPUT_TOKEN_THRESHOLD = 256


async def run_recommendation_refresh() -> None:
    """
    Identify apps using expensive models for tasks where cheaper models suffice.

    Heuristic: high call volume + low average output tokens on a premium model
    → likely overprovisioned. Compute savings delta and store recommendation.

    Existing non-dismissed recommendations for the same app+model pair are
    replaced (upsert by deleting old then inserting new).
    """
    if _session_factory is None:
        return

    start = time.perf_counter()
    recs_created = 0

    try:
        async with _session_factory() as db:
            ai_enabled = await get_setting_bool(
                db, "insights.recommendations.ai_text", False
            )

            now = datetime.now(timezone.utc)
            window_start = now - timedelta(days=7)

            # Aggregate by app + model over last 7 days
            usage_q = await db.execute(text("""
                SELECT
                    a.app_id              AS app_uuid,
                    a.team_id             AS team_uuid,
                    a.app_name,
                    ua.model,
                    ua.provider,
                    SUM(ua.call_count)    AS total_calls,
                    SUM(ua.output_tokens) AS total_output_tokens,
                    SUM(ua.total_cost)    AS total_cost_7d,
                    AVG(ua.output_tokens::float / NULLIF(ua.call_count, 0))
                                          AS avg_output_per_call
                FROM usage_aggregates ua
                JOIN apps a ON a.id = ua.app_id
                WHERE ua.granularity = 'daily'
                  AND ua.period_start >= :window_start
                  AND ua.call_count > 0
                GROUP BY a.app_id, a.team_id, a.app_name, ua.model, ua.provider
                HAVING SUM(ua.call_count) >= 100
                ORDER BY SUM(ua.total_cost) DESC
            """), {"window_start": sqlite_dt(window_start)})

            rows = usage_q.all()

            for row in rows:
                model = (row.model or "").lower()
                provider = (row.provider or "").lower()
                avg_out = float(row.avg_output_per_call or 0)
                calls_7d = int(row.total_calls or 0)
                cost_7d = float(row.total_cost_7d or 0)

                # Find a suggested cheaper model
                suggested = None
                for prefix, suggestion in _MODEL_SUGGESTIONS.items():
                    if model.startswith(prefix.lower()):
                        suggested = suggestion
                        break

                if not suggested:
                    continue

                # Only recommend if output tokens suggest simple tasks
                if avg_out > _LOW_OUTPUT_TOKEN_THRESHOLD:
                    continue

                # Compute savings using pricing module
                try:
                    from orchestrator.core.pricing import estimate_cost
                    calls_per_day = calls_7d / 7.0
                    # Estimate with typical token distribution
                    avg_in = 500  # conservative input estimate
                    _, _, cost_current = estimate_cost(
                        provider, model, int(avg_in), int(avg_out)
                    )
                    _, _, cost_suggested = estimate_cost(
                        provider, suggested, int(avg_in), int(avg_out)
                    )
                    savings_per_call = max(0.0, float(cost_current) - float(cost_suggested))
                    monthly_savings = savings_per_call * calls_per_day * 30
                except Exception:
                    # Fallback: estimate 60% savings for major tier drop
                    monthly_savings = cost_7d * (30 / 7) * 0.60

                if monthly_savings < 1.0:
                    continue  # Not worth recommending for < $1/month

                confidence = "high" if avg_out < 100 else "medium"

                # Delete any existing undismissed recommendation for this app+model
                await db.execute(text("""
                    DELETE FROM optimization_recommendations
                    WHERE app_id = :app_id
                      AND current_model = :model
                      AND dismissed_at IS NULL
                      AND applied_at IS NULL
                """), {"app_id": str(row.app_uuid), "model": row.model})

                rec_text = None
                if ai_enabled:
                    rec_text = await _ai_explain(
                        system=(
                            "You are a cost optimization assistant. Write one concise sentence "
                            "(max 30 words) recommending a cheaper AI model. Be specific about "
                            "the savings and why the cheaper model is sufficient. No markdown."
                        ),
                        user=(
                            f"App '{row.app_name}' makes {int(calls_per_day):.0f} calls/day "
                            f"to {row.model} with avg {avg_out:.0f} output tokens. "
                            f"Suggest switching to {suggested}. "
                            f"Estimated monthly savings: ${monthly_savings:.2f}."
                        ),
                        max_tokens=80,
                    )

                rec = OptimizationRecommendation(
                    team_id=str(row.team_uuid),
                    app_id=str(row.app_uuid),
                    current_model=row.model,
                    suggested_model=suggested,
                    provider=provider,
                    call_volume_basis=calls_7d,
                    estimated_monthly_savings=Decimal(str(round(monthly_savings, 8))),
                    confidence=confidence,
                    recommendation_text=rec_text.strip() if rec_text else None,
                )
                db.add(rec)
                recs_created += 1

            await db.commit()

        elapsed = time.perf_counter() - start
        logger.info(
            "Recommendation refresh complete",
            extra={"recommendations": recs_created, "duration_ms": round(elapsed * 1000)},
        )

    except Exception as exc:
        logger.error("Recommendation refresh failed", exc_info=exc)


# ── Prompt Efficiency Auditor ──────────────────────────────────────────────────
#
# Analyses token distribution patterns per app/model to identify structural
# waste without reading prompt content.  Runs on the cold path (background).
#
# What it surfaces:
#   - System prompt overhead: high input_tokens with low variance → fixed cost
#   - Output bloat: disproportionately large output tokens per call
#   - Input/output ratio anomalies: endpoints where input >> output (prompt waste)
#
# Produces PromptEfficiencyInsight rows (stored as OptimizationRecommendation
# with confidence="efficiency_audit" to reuse existing model/UI).

# Threshold: input/output ratio above this = likely system-prompt-heavy
_HIGH_INPUT_RATIO_THRESHOLD = 8.0
# Minimum calls to consider an app/model pair for audit
_MIN_CALLS_FOR_AUDIT = 50
# Minimum input tokens avg to be worth flagging
_MIN_INPUT_TOKENS_AVG = 1000


async def run_prompt_efficiency_audit() -> None:
    """
    Identify apps with structurally inefficient prompt patterns.

    Builds a cost fingerprint per (app, model) from token distribution:
      - avg_input_tokens, stddev_input_tokens → high avg + low stddev = large static prompt
      - avg_output_tokens → low output for high input = overprovisioned context
      - input/output ratio → >8:1 ratio suggests prompt compression opportunity

    Recommendations quantify savings: "Compressing to N tokens saves $X/month."
    """
    if _session_factory is None:
        return

    start = time.perf_counter()
    insights_created = 0

    try:
        async with _session_factory() as db:
            ai_enabled = await get_setting_bool(
                db, "insights.efficiency.ai_text", False
            )

            now = datetime.now(timezone.utc)
            window_start = now - timedelta(days=14)

            # Aggregate token distribution stats per app + model over last 14 days
            stats_q = await db.execute(text("""
                SELECT
                    ur.app_id,
                    a.app_name,
                    ur.team_id,
                    ur.model,
                    ur.provider,
                    COUNT(*)                              AS call_count,
                    AVG(CAST(ur.input_tokens AS FLOAT))   AS avg_input,
                    AVG(CAST(ur.output_tokens AS FLOAT))  AS avg_output,
                    SUM(ur.total_cost)                    AS total_cost_14d,
                    SUM(ur.input_cost)                    AS total_input_cost_14d
                FROM usage_records ur
                JOIN apps a ON a.id = ur.app_id
                WHERE ur.timestamp >= :window_start
                  AND ur.input_tokens IS NOT NULL
                  AND ur.input_tokens > 0
                  AND ur.output_tokens IS NOT NULL
                GROUP BY ur.app_id, a.app_name, ur.team_id, ur.model, ur.provider
                HAVING COUNT(*) >= :min_calls
                   AND AVG(CAST(ur.input_tokens AS FLOAT)) >= :min_input
                ORDER BY SUM(ur.total_cost) DESC
                LIMIT 100
            """), {
                "window_start": sqlite_dt(window_start),
                "min_calls": _MIN_CALLS_FOR_AUDIT,
                "min_input": _MIN_INPUT_TOKENS_AVG,
            })

            rows = stats_q.all()

            for row in rows:
                avg_in = float(row.avg_input or 0)
                avg_out = float(row.avg_output or 1)
                calls = int(row.call_count or 0)
                float(row.total_cost_14d or 0)
                input_cost_14d = float(row.total_input_cost_14d or 0)
                ratio = avg_in / max(avg_out, 1)

                if ratio < _HIGH_INPUT_RATIO_THRESHOLD:
                    continue  # Input/output ratio is reasonable

                # Estimate savings from compressing input by 50-75%
                # (conservative — most system prompts can be compressed 60-80%)
                compression_factor = 0.25  # keep 25% of current input
                input_savings_pct = 1.0 - compression_factor
                monthly_input_savings = (input_cost_14d / 14) * 30 * input_savings_pct

                if monthly_input_savings < 5.0:
                    continue  # Not worth flagging for < $5/month

                calls_per_day = calls / 14.0

                # Delete existing efficiency audit for this app+model
                await db.execute(text("""
                    DELETE FROM optimization_recommendations
                    WHERE app_id = :app_id
                      AND current_model = :model
                      AND confidence = 'efficiency_audit'
                      AND dismissed_at IS NULL
                      AND applied_at IS NULL
                """), {"app_id": str(row.app_id), "model": row.model})

                rec_text = None
                if ai_enabled:
                    rec_text = await _ai_explain(
                        system=(
                            "You are a prompt efficiency advisor. Write one actionable sentence "
                            "(max 40 words) about reducing input token waste. Be specific about "
                            "the numbers. No markdown."
                        ),
                        user=(
                            f"App '{row.app_name}' sends avg {avg_in:.0f} input tokens and "
                            f"gets avg {avg_out:.0f} output tokens per call to {row.model} "
                            f"({calls_per_day:.0f} calls/day, {ratio:.1f}:1 input/output ratio). "
                            f"Input cost: ${input_cost_14d/14*30:.2f}/month. "
                            f"Compressing prompts to ~{avg_in*compression_factor:.0f} tokens "
                            f"saves ~${monthly_input_savings:.2f}/month."
                        ),
                        max_tokens=100,
                    )

                rec = OptimizationRecommendation(
                    team_id=str(row.team_id),
                    app_id=str(row.app_id),
                    current_model=row.model or "unknown",
                    suggested_model=row.model or "unknown",  # same model, just compress
                    provider=row.provider or "unknown",
                    call_volume_basis=calls,
                    estimated_monthly_savings=Decimal(str(round(monthly_input_savings, 8))),
                    confidence="efficiency_audit",
                    recommendation_text=rec_text.strip() if rec_text else (
                        f"System prompt on {row.app_name} averages {avg_in:.0f} input tokens "
                        f"({ratio:.0f}:1 input/output ratio, {calls_per_day:.0f} calls/day). "
                        f"Compressing to ~{avg_in*compression_factor:.0f} tokens saves "
                        f"~${monthly_input_savings:.0f}/month."
                    ),
                )
                db.add(rec)
                insights_created += 1

            await db.commit()

        elapsed = time.perf_counter() - start
        logger.info(
            "Prompt efficiency audit complete",
            extra={"insights": insights_created, "duration_ms": round(elapsed * 1000)},
        )

    except Exception as exc:
        logger.error("Prompt efficiency audit failed", exc_info=exc)


# ── Task loop factory ──────────────────────────────────────────────────────────

async def insights_task_loop(
    task_key: str,
    run_fn,
    default_interval_seconds: int,
) -> None:
    """
    Generic insights task loop.
    Reads interval from system_settings on each iteration — hot-reloadable.
    Checks every 30 seconds whether it's time to run, then sleeps the remainder.

    Args:
        task_key: settings key prefix e.g. "task.anomaly_scan"
        run_fn:   async coroutine function to execute
        default_interval_seconds: fallback if setting not found
    """
    enabled_key  = f"{task_key}.enabled"
    interval_key = f"{task_key}.interval_seconds"

    logger.info("Insights task started: %s (default interval: %ds)",
                task_key, default_interval_seconds)

    last_run: float = 0.0  # epoch seconds of last successful run

    while True:
        try:
            await asyncio.sleep(30)  # check every 30s

            # Read current settings
            if _session_factory is None:
                continue

            async with _session_factory() as db:
                enabled  = await get_setting_bool(db, enabled_key, True)
                interval = await get_setting_int(db, interval_key,
                                                  default_interval_seconds)

            if not enabled:
                continue

            now = time.monotonic()
            if now - last_run < interval:
                continue  # Not time yet

            await run_fn()
            last_run = time.monotonic()

        except asyncio.CancelledError:
            logger.info("Insights task stopping: %s", task_key)
            break
        except Exception as exc:
            logger.error("Insights task error (%s): %s", task_key, exc,
                         exc_info=True)
            # Continue — don't let a task failure kill the loop
