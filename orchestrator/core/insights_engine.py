async def get_setting(db, key: str) -> str:
    """Read a setting from system_settings, falling back to built-in defaults."""
    row = await db.get(SystemSetting, key)
    if row is not None:
        return row.value
    return _DEFAULTS.get(key, "")


async def get_setting_int(db, key: str, default: int = 0) -> int:
    val = await get_setting(db, key)
    try:
        return int(val)
    except (ValueError, TypeError):
        return default


async def get_setting_float(db, key: str, default: float = 0.0) -> float:
    val = await get_setting(db, key)
    try:
        return float(val)
    except (ValueError, TypeError):
        return default


async def get_setting_bool(db, key: str, default: bool = False) -> bool:
    val = await get_setting(db, key)
    return val.lower() in ("true", "1", "yes", "on")


# ── Claude API helper ──────────────────────────────────────────────────────────

def _anthropic_api_key() -> str:
    """The Anthropic key the operator configured for AI features, or "".

    Reuses the assistant configuration (the same place the in-app assistant
    reads its key): the key counts only when MODUS_ASSISTANT_PROVIDER is
    ``anthropic``. There is deliberately no environment-variable fallback, so
    nothing is sent anywhere unless the operator configured it.
    """
    from orchestrator.core.config import get_settings

    cfg = get_settings()
    if (cfg.assistant_provider or "").lower().strip() != "anthropic":
        return ""
    return (cfg.assistant_api_key or "").strip()


_warned_no_key = False


def _claude_generate(system: str, user: str, max_tokens: int, api_key: str) -> Optional[str]:
    """
    Synchronous Anthropic Messages API call. Run via asyncio.to_thread().
    Returns None on any error (after logging a warning) -- callers fall back
    to deterministic text.
    """
    try:
        payload = json.dumps({
            "model": "claude-haiku-4-5-20251001",  # cheapest model -- explanations only
            "max_tokens": max_tokens,
            "system": system,
            "messages": [{"role": "user", "content": user}],
        }).encode()

        req = urllib_request.Request(
            "https://api.anthropic.com/v1/messages",
            data=payload,
            headers={
                "Content-Type": "application/json",
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
            },
            method="POST",
        )
        with urllib_request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode())
            blocks = data.get("content", [])
            return next((b["text"] for b in blocks if b.get("type") == "text"), None)
    except Exception as exc:
        # Never log the request (it carries the key header) -- just the cause.
        logger.warning(
            "Anthropic call for AI insight text failed (%s: %s); using built-in text",
            type(exc).__name__, exc,
        )
        return None


async def _ai_explain(system: str, user: str, max_tokens: int = 300) -> Optional[str]:
    """
    Produce explanation text. The only outbound call in this module, and it
    is opt-in twice over: callers invoke it only when the operator enabled the
    relevant ``insights.*`` setting (all default off), and it sends nothing
    unless an Anthropic API key is configured. Otherwise -- or if the call
    fails -- the deterministic built-in text is returned.
    """
    global _warned_no_key
    api_key = _anthropic_api_key()
    if not api_key:
        if not _warned_no_key:
            _warned_no_key = True
            logger.warning(
                "AI insight text is enabled but no Anthropic API key is configured "
                "(set MODUS_ASSISTANT_PROVIDER=anthropic and MODUS_ASSISTANT_API_KEY); "
                "using built-in text and making no outbound call"
            )
        return _fallback_explain(user)
    result = await asyncio.to_thread(_claude_generate, system, user, max_tokens, api_key)
    if result is not None:
        return result
    return _fallback_explain(user)


def _fallback_explain(context: str) -> str:
    """
    Zero-cost deterministic fallback when AI text is unavailable.
    Returns a simple template-based explanation from the context string.
    """
    if "anomaly" in context.lower() or "z-score" in context.lower():
        return "Spend anomaly detected — usage significantly exceeds the historical baseline. Review recent activity."
    if "recommend" in context.lower() or "switch" in context.lower():
        return "Consider switching to a cheaper model for this workload — output token usage suggests simple tasks."
    return "Analysis generated without AI — configure an Anthropic key and enable the insights AI settings for detailed explanations."


# ── Anomaly detection ──────────────────────────────────────────────────────────

async def run_anomaly_scan() -> None:
    """
    Scan for statistical anomalies across all teams.

    For each (team, app, metric) combination:
      1. Compute mean and std_dev from the last N days of daily aggregates
      2. Compute the last-1-hour actual value from hourly aggregates
      3. If z_score >= threshold, create an AnomalyEvent
      4. If AI explanations are enabled and no explanation exists, generate one

    NOTE: Requires PostgreSQL (uses STDDEV_POP, date_trunc). Skipped on SQLite.

    Safe to run multiple times — deduplicates by checking for existing events
    in the same 1-hour window.
    """
    if _session_factory is None:
        return
    from orchestrator.core.config import settings as _cfg
    if _cfg.is_sqlite:
        logger.debug("Anomaly scan skipped (SQLite — requires PostgreSQL)")
        return

    start = time.perf_counter()
    events_fired = 0

    try:
        async with _session_factory() as db:
            zscore_threshold = await get_setting_float(
                db, "insights.anomaly.zscore_threshold", 3.0
            )
            baseline_days = await get_setting_int(
                db, "insights.anomaly.baseline_days", 14
            )
            ai_enabled = await get_setting_bool(
                db, "insights.anomaly.ai_explanations", False
            )

            now = datetime.now(timezone.utc)
            baseline_start = now - timedelta(days=baseline_days)
            current_window_start = now - timedelta(hours=1)

            # Compute per-app daily cost baseline (mean + std_dev)
            baseline_q = await db.execute(text("""
                SELECT
                    app_id,
                    team_id,
                    'cost' AS metric,
                    AVG(total_cost)                         AS mean_val,
                    STDDEV_POP(total_cost)                  AS std_val,
                    COUNT(*)                                AS sample_count
                FROM usage_aggregates
                WHERE granularity = 'daily'
                  AND period_start >= :baseline_start
                  AND period_start < date_trunc('day', NOW() AT TIME ZONE 'UTC')
                GROUP BY app_id, team_id
                HAVING COUNT(*) >= 3
            """), {"baseline_start": sqlite_dt(baseline_start)})

            baselines = {
                (str(r.app_id), str(r.team_id), r.metric): {
                    "mean": float(r.mean_val or 0),
                    "std":  float(r.std_val or 0),
                    "n":    r.sample_count,
                }
                for r in baseline_q.all()
            }

            # Compute current-hour actual values
            current_q = await db.execute(text("""
                SELECT
                    app_id,
                    team_id,
                    SUM(total_cost)   AS cost_actual,
                    SUM(call_count)   AS calls_actual
                FROM usage_aggregates
                WHERE granularity = 'hourly'
                  AND period_start >= :window_start
                GROUP BY app_id, team_id
            """), {"window_start": sqlite_dt(current_window_start)})

            current_by_app: dict[tuple, dict] = {}
            for r in current_q.all():
                current_by_app[(str(r.app_id), str(r.team_id))] = {
                    "cost":  float(r.cost_actual or 0),
                    "calls": float(r.calls_actual or 0),
                }

            # Check for existing events in this hour window (dedup)
            existing_q = await db.execute(text("""
                SELECT app_id, metric
                FROM anomaly_events
                WHERE detected_at >= :window_start
            """), {"window_start": sqlite_dt(current_window_start)})
            already_fired = {
                (str(r.app_id), r.metric) for r in existing_q.all()
            }

            for (app_id, team_id, metric), baseline in baselines.items():
                if baseline["std"] < 0.0001:
                    continue  # No variance — skip

                actual_data = current_by_app.get((app_id, team_id), {})
                actual = actual_data.get(metric, 0.0)

                # Normalise hourly actual to daily-equivalent for comparison
                hour_of_day = now.hour + 1  # hours elapsed today
                daily_equivalent = (actual / max(hour_of_day, 1)) * 24

                z = (daily_equivalent - baseline["mean"]) / baseline["std"]

                if z < zscore_threshold:
                    continue

                if (app_id, metric) in already_fired:
                    continue

                # Determine severity
                if z >= 6.0:
                    severity = "critical"
                elif z >= 4.5:
                    severity = "high"
                elif z >= zscore_threshold + 0.5:
                    severity = "medium"
                else:
                    severity = "low"

                # Fetch app name for AI context
                app_row = await db.get(App, app_id)
                app_name = app_row.app_name if app_row else app_id

                # Create the anomaly event
                event_id = __import__("uuid").uuid4().__str__()
                event = AnomalyEvent(
                    id=event_id,
                    team_id=team_id,
                    app_id=app_id,
                    metric=metric,
                    severity=severity,
                    z_score=Decimal(str(round(z, 4))),
                    baseline_value=Decimal(str(round(baseline["mean"], 8))),
                    actual_value=Decimal(str(round(daily_equivalent, 8))),
                    window_hours=1,
                    metadata_={
                        "baseline_std":  round(baseline["std"], 8),
                        "baseline_days": baseline_days,
                        "sample_count":  baseline["n"],
                        "raw_actual_1h": round(actual, 8),
                    },
                )
                db.add(event)
                await db.flush()

                # Generate AI explanation if enabled
                if ai_enabled and severity in ("high", "critical"):
                    explanation = await _ai_explain(
                        system=(
                            "You are a cost analysis assistant. Write one concise sentence "
                            "(max 25 words) explaining an AI spend anomaly. Be specific and "
                            "actionable. No markdown, no bullet points."
                        ),
                        user=(
                            f"App '{app_name}' has a cost anomaly: "
                            f"z-score={z:.1f}, severity={severity}. "
                            f"14-day daily average: ${baseline['mean']:.4f}. "
                            f"Current hourly rate annualised to ${daily_equivalent:.4f}/day. "
                            f"Provide one sentence explanation."
                        ),
                        max_tokens=80,
                    )
                    if explanation:
                        event.ai_explanation = explanation.strip()

                events_fired += 1
                logger.info(
                    "Anomaly detected",
                    extra={
                        "app_id": app_id, "metric": metric,
                        "severity": severity, "z_score": round(z, 2),
                    },
                )

            await db.commit()

        elapsed = time.perf_counter() - start
        logger.debug(
            "Anomaly scan complete",
            extra={"events_fired": events_fired, "duration_ms": round(elapsed * 1000)},
        )

    except Exception as exc:
        logger.error("Anomaly scan failed", exc_info=exc)


# ── Spend forecasting ──────────────────────────────────────────────────────────

def _ols_forecast(
    xs: list[float], ys: list[float]
) -> tuple[float, float, float]:
    """
    Ordinary Least Squares linear regression.
    Returns (slope, intercept, r_squared).
    Pure Python — no numpy, no scipy.
    """
    n = len(xs)
    if n < 2:
        return 0.0, ys[0] if ys else 0.0, 0.0

    mx = sum(xs) / n
    my = sum(ys) / n

    ss_xy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    ss_xx = sum((x - mx) ** 2 for x in xs)

    if ss_xx < 1e-10:
        return 0.0, my, 0.0

    slope = ss_xy / ss_xx
    intercept = my - slope * mx

    # R²
    ss_res = sum((y - (slope * x + intercept)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys)
    r_sq = 1.0 - (ss_res / ss_tot) if ss_tot > 1e-10 else 0.0

    return slope, intercept, max(0.0, min(1.0, r_sq))


async def run_forecast_update() -> None:
    """
    Compute linear regression spend forecasts for each team and org-wide.
    Writes one SpendForecast row per team per run.
    No external API calls — pure arithmetic.

    NOTE: Requires PostgreSQL (uses date_trunc, ::date cast). Skipped on SQLite.
    """
    if _session_factory is None:
        return
    from orchestrator.core.config import settings as _cfg
    if _cfg.is_sqlite:
        logger.debug("Forecast update skipped (SQLite — requires PostgreSQL)")
        return

    start = time.perf_counter()

    try:
        async with _session_factory() as db:
            now = datetime.now(timezone.utc)
            basis_days = 28
            window_start = now - timedelta(days=basis_days)
            period_label = now.strftime("%Y-%m")

            # Days remaining in month / quarter / year
            days_in_month = (
                datetime(now.year, now.month % 12 + 1, 1, tzinfo=timezone.utc)
                if now.month < 12
                else datetime(now.year + 1, 1, 1, tzinfo=timezone.utc)
            )
            days_remaining_month = (days_in_month - now).days

            # Fetch daily totals per team
            daily_q = await db.execute(text("""
                SELECT
                    team_id,
                    date_trunc('day', period_start)::date  AS day,
                    SUM(total_cost)                        AS daily_cost
                FROM usage_aggregates
                WHERE granularity = 'daily'
                  AND period_start >= :window_start
                GROUP BY team_id, date_trunc('day', period_start)::date
                ORDER BY team_id, day
            """), {"window_start": sqlite_dt(window_start)})

            # Group by team
            team_days: dict[str, list[tuple[int, float]]] = {}
            for r in daily_q.all():
                tid = str(r.team_id)
                if tid not in team_days:
                    team_days[tid] = []
                team_days[tid].append((r.day.toordinal(), float(r.daily_cost or 0)))

            teams_processed = 0
            for team_id, day_costs in team_days.items():
                if len(day_costs) < 3:
                    continue

                xs = [float(d - day_costs[0][0]) for d, _ in day_costs]
                ys = [c for _, c in day_costs]

                slope, intercept, r_sq = _ols_forecast(xs, ys)

                # MTD actual
                mtd_q = await db.execute(text("""
                    SELECT COALESCE(SUM(total_cost), 0) AS mtd
                    FROM usage_aggregates
                    WHERE team_id = :tid
                      AND granularity = 'daily'
                      AND period_start >= date_trunc('month', NOW() AT TIME ZONE 'UTC')
                """), {"tid": team_id})
                mtd = float((mtd_q.scalar() or 0))

                # Project remaining days
                last_x = xs[-1]
                eom_additional = sum(
                    max(0.0, slope * (last_x + i) + intercept)
                    for i in range(1, days_remaining_month + 1)
                )
                forecast_eom = Decimal(str(round(mtd + eom_additional, 8)))

                # Rough EOQ — project from now to end of quarter
                q_end_month = ((now.month - 1) // 3 + 1) * 3
                q_end = datetime(
                    now.year if q_end_month <= 12 else now.year + 1,
                    q_end_month % 12 or 12, 28, tzinfo=timezone.utc
                )
                days_to_eoq = max(0, (q_end - now).days)
                eoq_additional = sum(
                    max(0.0, slope * (last_x + i) + intercept)
                    for i in range(1, days_to_eoq + 1)
                )
                forecast_eoq = Decimal(str(round(mtd + eoq_additional, 8)))

                # Trend vs same period last month
                prior_start = window_start - timedelta(days=basis_days)
                prior_q = await db.execute(text("""
                    SELECT COALESCE(SUM(total_cost), 0) AS prior
                    FROM usage_aggregates
                    WHERE team_id = :tid
                      AND granularity = 'daily'
                      AND period_start >= :prior_start
                      AND period_start < :window_start
                """), {"tid": team_id, "prior_start": sqlite_dt(prior_start),
                       "window_start": sqlite_dt(window_start)})
                prior_total = float(prior_q.scalar() or 0)
                current_total = sum(ys)
                trend_pct = (
                    Decimal(str(round(
                        ((current_total - prior_total) / prior_total) * 100, 4
                    )))
                    if prior_total > 0.001 else None
                )

                forecast = SpendForecast(
                    team_id=team_id,
                    period_label=period_label,
                    mtd_actual=Decimal(str(round(mtd, 8))),
                    forecast_eom=forecast_eom,
                    forecast_eoq=forecast_eoq,
                    trend_pct=trend_pct,
                    r_squared=Decimal(str(round(r_sq, 4))),
                    basis_days=basis_days,
                )
                db.add(forecast)
                teams_processed += 1

            await db.commit()

        elapsed = time.perf_counter() - start
        logger.info(
            "Forecast update complete",
            extra={"teams": teams_processed, "duration_ms": round(elapsed * 1000)},
        )

    except Exception as exc:
        logger.error("Forecast update failed", exc_info=exc)


