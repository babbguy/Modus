"""
Modus — Insights Engine
================================
Three background tasks that compute analytics from existing usage data.

All computation runs inside the existing FastAPI process on the async event
loop. No separate process, no ML library, no message queue.

Algorithms
----------
Anomaly detection:
    Z-score = (actual - mean) / std_dev over a configurable baseline window.
    Baseline computed from daily usage_aggregates (already maintained by the
    aggregator). Pure SQL arithmetic — no scipy, no sklearn.

Spend forecasting:
    Ordinary least squares linear regression over last N days of daily totals.
    OLS in pure Python (4 lines of arithmetic). Extrapolates to EOM, EOQ, EOY.
    R² included as confidence signal.

Model recommendations:
    Identifies apps where high-volume calls go to expensive models with low
    average output tokens (signal of over-provisioning). Computes monthly
    savings delta using the SDK's pricing table. No ML required.

Claude API usage
----------------
OFF by default. Natural-language explanations are generated by Anthropic only
when BOTH (a) the operator sets the relevant system setting to "true"
(insights.anomaly.ai_explanations, insights.recommendations.ai_text,
insights.efficiency.ai_text) AND (b) an Anthropic API key is configured
(MODUS_ASSISTANT_PROVIDER=anthropic + MODUS_ASSISTANT_API_KEY). Otherwise no
request is made and deterministic built-in text is used. Results are cached on
the database row — never regenerated for the same event.

Estimated API cost: <$0.01 per anomaly explanation, <$0.02 per recommendation.
"""

